///   천안·전주·포항·창원 — 는 시 항목을 빼고 구 35개로 대체했다. 총 252개.
///   구가 없는 시·군(파주시·가평군 등)은 그대로 시·군 단위.
///   ⚠ 화성시는 일반구 미설치 상태라 아직 시 단위 — 설치되면 여기도 구로 쪼갤 것.
///
/// ⚠ [label] 은 화면에 그대로 뜨는 문자열이다. 같은 이름이 여러 시도에 있는
///   중구·동구·남구·서구·북구·강서구·고성군은 '서울 중구'처럼 시도를 앞에 붙였고,
///   유일한 이름은 '마포구'·'분당구'처럼 구명만 쓴다 (라벨 유일성은 테스트가 지킨다).
