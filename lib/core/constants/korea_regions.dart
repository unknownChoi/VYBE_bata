///
/// ⚠ **구가 있는 시는 시가 아니라 구를 넣는다.** 100만 안팎 도시를 시 하나로 두면
///   분당(성남)·일산(고양)·동탄(용인 옆) 같은 생활권이 전부 한 이름으로 뭉개진다.
